--------------------------------------------------------------------------------
-- Corlix Hub · Suporte TI · 01 · tabelas, triggers e view
-- Reexecutável (if not exists / create or replace).
--
-- suporte_config    -> canais de contato e prazo de confirmação, por empresa
-- suporte_sistema   -> status dos sistemas e aviso de instabilidade
-- suporte_assunto   -> os assuntos da tela e dos chamados
-- suporte_artigo    -> base de conhecimento
-- suporte_chamado   -> chamados (incidentes e solicitações)
-- suporte_mensagem  -> conversa do chamado
-- suporte_anexo     -> arquivos do chamado
--------------------------------------------------------------------------------
set define off

create table if not exists suporte_config (
  id_empresa           number primary key,
  ds_ramal             varchar2(30),
  ds_telefone          varchar2(30),
  ds_horario           varchar2(100),
  nr_dias_confirmacao  number(2) default 3 not null,
  constraint fk_suporte_config_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint ck_suporte_config_dias    check (nr_dias_confirmacao between 1 and 30)
);

create table if not exists suporte_sistema (
  id_sistema       number generated by default as identity primary key,
  id_empresa       number        not null,
  nm_sistema       varchar2(100) not null,
  nr_ordem         number(4)     default 10 not null,
  st_sistema       varchar2(12)  default 'OPERANDO' not null,
  ds_detalhe       varchar2(150),
  ds_aviso_titulo  varchar2(150),
  ds_aviso_texto   varchar2(500),
  dh_atualizacao   timestamp with time zone default systimestamp not null,
  usr_atualizacao  varchar2(255),
  constraint fk_suporte_sistema_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint ck_suporte_sistema_status  check (st_sistema in ('OPERANDO', 'INSTAVEL', 'MANUTENCAO', 'FORA')),
  constraint uq_suporte_sistema_nome    unique (id_empresa, nm_sistema)
);

create table if not exists suporte_assunto (
  id_assunto  number generated by default as identity primary key,
  id_empresa  number        not null,
  nm_assunto  varchar2(60)  not null,
  cd_icone    varchar2(20)  not null,
  nr_ordem    number(4)     default 10 not null,
  fl_ativo    varchar2(1)   default 'S' not null,
  constraint fk_suporte_assunto_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint ck_suporte_assunto_ativo   check (fl_ativo in ('S', 'N')),
  constraint uq_suporte_assunto_nome    unique (id_empresa, nm_assunto)
);

create table if not exists suporte_artigo (
  id_artigo       number generated by default as identity primary key,
  id_empresa      number         not null,
  id_assunto      number         not null,
  ds_titulo       varchar2(150)  not null,
  ds_resumo       varchar2(300),
  ds_corpo        varchar2(4000) not null,
  ds_palavras     varchar2(500),
  nr_min_leitura  number(3)      default 2 not null,
  nr_acessos      number         default 0 not null,
  fl_publicado    varchar2(1)    default 'S' not null,
  dh_atualizacao  timestamp with time zone default systimestamp not null,
  usr_atualizacao varchar2(255),
  constraint fk_suporte_artigo_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint fk_suporte_artigo_assunto foreign key (id_assunto) references suporte_assunto (id_assunto),
  constraint ck_suporte_artigo_public  check (fl_publicado in ('S', 'N')),
  constraint uq_suporte_artigo_titulo  unique (id_empresa, ds_titulo)
);

create index if not exists ix_suporte_artigo_assunto on suporte_artigo (id_assunto);

create table if not exists suporte_chamado (
  id_chamado             number generated by default as identity primary key,
  id_empresa             number         not null,
  id_solicitante         number         not null,
  tp_chamado             varchar2(3)    not null,
  id_assunto             number         not null,
  ds_titulo              varchar2(150)  not null,
  ds_descricao           varchar2(4000) not null,
  st_chamado             varchar2(20)   default 'ABERTO' not null,
  tp_prioridade          varchar2(5)    default 'MEDIA' not null,
  id_atendente           number,
  dt_previsao            date,
  ds_solucao             varchar2(4000),
  dt_limite_confirmacao  date,
  nr_reaberturas         number(3)      default 0 not null,
  tp_encerramento        varchar2(10),
  dh_abertura            timestamp with time zone default systimestamp not null,
  dh_atualizacao         timestamp with time zone default systimestamp not null,
  dh_resolucao           timestamp with time zone,
  dh_encerramento        timestamp with time zone,
  constraint fk_suporte_chamado_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_suporte_chamado_solicitante foreign key (id_solicitante) references colaborador (id_colaborador),
  constraint fk_suporte_chamado_atendente   foreign key (id_atendente)   references colaborador (id_colaborador),
  constraint fk_suporte_chamado_assunto     foreign key (id_assunto)     references suporte_assunto (id_assunto),
  constraint ck_suporte_chamado_tipo        check (tp_chamado in ('INC', 'REQ')),
  constraint ck_suporte_chamado_status      check (st_chamado in ('ABERTO', 'EM_ATENDIMENTO', 'AGUARDANDO_USUARIO', 'RESOLVIDO', 'ENCERRADO')),
  constraint ck_suporte_chamado_prioridade  check (tp_prioridade in ('BAIXA', 'MEDIA', 'ALTA')),
  constraint ck_suporte_chamado_encerra     check (tp_encerramento in ('CONFIRMADO', 'AUTOMATICO'))
);

create index if not exists ix_suporte_chamado_solicit on suporte_chamado (id_solicitante, st_chamado);
create index if not exists ix_suporte_chamado_fila    on suporte_chamado (id_empresa, st_chamado);
create index if not exists ix_suporte_chamado_atend   on suporte_chamado (id_atendente);
create index if not exists ix_suporte_chamado_assunto on suporte_chamado (id_assunto);
create index if not exists ix_suporte_chamado_limite  on suporte_chamado (st_chamado, dt_limite_confirmacao);

create table if not exists suporte_mensagem (
  id_mensagem  number generated by default as identity primary key,
  id_chamado   number         not null,
  id_autor     number,
  tp_autor     varchar2(12)   not null,
  ds_texto     varchar2(4000) not null,
  dh_envio     timestamp with time zone default systimestamp not null,
  constraint fk_suporte_mensagem_chamado foreign key (id_chamado) references suporte_chamado (id_chamado),
  constraint fk_suporte_mensagem_autor   foreign key (id_autor)   references colaborador (id_colaborador),
  constraint ck_suporte_mensagem_tipo    check (tp_autor in ('COLABORADOR', 'TI', 'SISTEMA'))
);

create index if not exists ix_suporte_mensagem_chamado on suporte_mensagem (id_chamado, id_mensagem);

-- id_mensagem nula: anexo enviado na abertura do chamado
create table if not exists suporte_anexo (
  id_anexo      number generated by default as identity primary key,
  id_chamado    number        not null,
  id_mensagem   number,
  nm_arquivo    varchar2(255) not null,
  ds_mime       varchar2(100) not null,
  nr_bytes      number        not null,
  bl_arquivo    blob          not null,
  usr_envio     varchar2(255),
  dh_envio      timestamp with time zone default systimestamp not null,
  constraint fk_suporte_anexo_chamado  foreign key (id_chamado)  references suporte_chamado (id_chamado),
  constraint fk_suporte_anexo_mensagem foreign key (id_mensagem) references suporte_mensagem (id_mensagem)
);

create index if not exists ix_suporte_anexo_chamado  on suporte_anexo (id_chamado);
create index if not exists ix_suporte_anexo_mensagem on suporte_anexo (id_mensagem);

-- Os formulários das páginas 41 e 43 gravam direto na tabela: a data e o autor
-- da alteração vêm daqui, e a empresa é a da sessão quando o formulário não manda.
create or replace trigger trg_suporte_sistema_aud
  before insert or update on suporte_sistema
  for each row
begin
  :new.dh_atualizacao  := systimestamp;
  :new.usr_atualizacao := coalesce(sys_context('APEX$SESSION', 'APP_USER'), sys_context('USERENV', 'SESSION_USER'));
  if :new.id_empresa is null then
    :new.id_empresa := to_number(v('G_ID_EMPRESA'));
  end if;
end;
/

-- Contar um acesso não é editar o artigo: só muda a data se outro campo mudou.
create or replace trigger trg_suporte_artigo_aud
  before insert or update of id_assunto, ds_titulo, ds_resumo, ds_corpo, ds_palavras, nr_min_leitura, fl_publicado
  on suporte_artigo
  for each row
begin
  :new.dh_atualizacao  := systimestamp;
  :new.usr_atualizacao := coalesce(sys_context('APEX$SESSION', 'APP_USER'), sys_context('USERENV', 'SESSION_USER'));
  if :new.id_empresa is null then
    :new.id_empresa := to_number(v('G_ID_EMPRESA'));
  end if;
end;
/

-- Fila da página 38. A empresa é filtrada na página (:G_ID_EMPRESA).
create or replace view vw_suporte_fila as
select c.id_chamado,
       c.id_empresa,
       c.tp_chamado || '-' || c.id_chamado as cd_chamado,
       case c.tp_chamado when 'INC' then 'Incidente' else 'Solicitação' end as ds_tipo,
       c.ds_titulo,
       a.nm_assunto,
       s.nome_completo as nm_solicitante,
       r.nome_completo as nm_atendente,
       c.st_chamado,
       case c.st_chamado
         when 'ABERTO'             then 'Na fila'
         when 'EM_ATENDIMENTO'     then 'Em atendimento'
         when 'AGUARDANDO_USUARIO' then 'Aguardando colaborador'
         when 'RESOLVIDO'          then 'Resolvido'
         else 'Encerrado'
       end as ds_status,
       c.tp_prioridade,
       case c.tp_prioridade when 'ALTA' then 'Alta' when 'MEDIA' then 'Média' else 'Baixa' end as ds_prioridade,
       case c.tp_prioridade when 'ALTA' then 1 when 'MEDIA' then 2 else 3 end as nr_prioridade,
       c.dt_previsao,
       c.dt_limite_confirmacao,
       c.nr_reaberturas,
       c.dh_abertura,
       c.dh_atualizacao
  from suporte_chamado c
  join suporte_assunto a on a.id_assunto = c.id_assunto
  join colaborador s on s.id_colaborador = c.id_solicitante
  left join colaborador r on r.id_colaborador = c.id_atendente;
