--------------------------------------------------------------------------------
-- Corlix Hub · Ponto eletrônico · 01 · tabelas, trigger e view
-- Reexecutável (if not exists / create or replace).
--
-- ponto_jornada             -> horário de trabalho, por empresa
-- ponto_colaborador         -> jornada e início do controle de cada colaborador
-- ponto_feriado             -> dias sem expediente, por empresa
-- ponto_ajuste              -> pedidos de ajuste e abono, com a resposta do gestor
-- ponto_marcacao            -> marcações. Só aceita INSERT: ajuste vira linha nova
-- ponto_espelho_assinatura  -> assinatura do espelho mensal pelo colaborador
--
-- Datas locais (dt_referencia, dh_marcacao) estão no fuso da empresa
-- (pkg_historico_carreira.fn_data_local). dh_registro guarda o instante real.
--------------------------------------------------------------------------------
set define off

create table if not exists ponto_jornada (
  id_jornada          number generated by default as identity primary key,
  id_empresa          number        not null,
  nm_jornada          varchar2(100) not null,
  nr_min_entrada      number(4)     not null,
  nr_min_saida        number(4)     not null,
  nr_min_intervalo    number(4)     default 60  not null,
  nr_min_diarios      number(4)     default 480 not null,
  nr_min_semanais     number(5)     default 2400 not null,
  nr_min_tolerancia   number(3)     default 10  not null,
  nr_meses_validade   number(2)     default 6   not null,
  fl_padrao           varchar2(1)   default 'N' not null,
  constraint fk_ponto_jornada_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint ck_ponto_jornada_padrao  check (fl_padrao in ('S', 'N')),
  constraint ck_ponto_jornada_horario check (nr_min_saida > nr_min_entrada),
  constraint uq_ponto_jornada_nome    unique (id_empresa, nm_jornada)
);

create table if not exists ponto_colaborador (
  id_colaborador      number primary key,
  id_empresa          number not null,
  id_jornada          number not null,
  dt_inicio_controle  date   not null,
  ds_local            varchar2(100),
  constraint fk_ponto_colab_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint fk_ponto_colab_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_ponto_colab_jornada     foreign key (id_jornada)     references ponto_jornada (id_jornada)
);

create table if not exists ponto_feriado (
  id_feriado  number generated by default as identity primary key,
  id_empresa  number        not null,
  dt_feriado  date          not null,
  nm_feriado  varchar2(100) not null,
  constraint fk_ponto_feriado_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint uq_ponto_feriado unique (id_empresa, dt_feriado)
);

create table if not exists ponto_ajuste (
  id_ajuste       number generated by default as identity primary key,
  id_empresa      number         not null,
  id_colaborador  number         not null,
  dt_referencia   date           not null,
  tp_ajuste       varchar2(10)   not null,
  tp_marcacao     varchar2(10),
  dh_solicitada   date,
  ds_motivo       varchar2(2000) not null,
  st_ajuste       varchar2(10)   default 'PENDENTE' not null,
  dh_pedido       timestamp with time zone default systimestamp not null,
  id_aprovador    number,
  usr_resposta    varchar2(255),
  dh_resposta     timestamp with time zone,
  ds_resposta     varchar2(2000),
  constraint fk_ponto_ajuste_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_ponto_ajuste_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint fk_ponto_ajuste_aprovador   foreign key (id_aprovador)   references colaborador (id_colaborador),
  constraint ck_ponto_ajuste_tipo        check (tp_ajuste in ('MARCACAO', 'ABONO')),
  constraint ck_ponto_ajuste_marcacao    check (tp_marcacao in ('ENTRADA', 'INTERVALO', 'RETORNO', 'SAIDA')),
  constraint ck_ponto_ajuste_status      check (st_ajuste in ('PENDENTE', 'APROVADO', 'RECUSADO')),
  constraint ck_ponto_ajuste_coerente    check (
    (tp_ajuste = 'MARCACAO' and tp_marcacao is not null and dh_solicitada is not null)
    or (tp_ajuste = 'ABONO' and tp_marcacao is null and dh_solicitada is null))
);

create index if not exists ix_ponto_ajuste_colab on ponto_ajuste (id_colaborador, dt_referencia);
create index if not exists ix_ponto_ajuste_fila  on ponto_ajuste (id_empresa, st_ajuste);

create table if not exists ponto_marcacao (
  id_marcacao     number generated by default as identity primary key,
  id_empresa      number       not null,
  id_colaborador  number       not null,
  dt_referencia   date         not null,
  tp_marcacao     varchar2(10) not null,
  dh_marcacao     date         not null,
  dh_registro     timestamp with time zone default systimestamp not null,
  ds_origem       varchar2(10) default 'NAVEGADOR' not null,
  id_ajuste       number,
  ds_ip           varchar2(64),
  ds_navegador    varchar2(400),
  usr_registro    varchar2(255),
  constraint fk_ponto_marcacao_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_ponto_marcacao_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint fk_ponto_marcacao_ajuste      foreign key (id_ajuste)      references ponto_ajuste (id_ajuste),
  constraint ck_ponto_marcacao_tipo        check (tp_marcacao in ('ENTRADA', 'INTERVALO', 'RETORNO', 'SAIDA')),
  constraint ck_ponto_marcacao_origem      check (ds_origem in ('NAVEGADOR', 'AJUSTE', 'DEMO'))
);

-- Uma marcação original por tipo e dia (barra clique duplo e duas abas abertas);
-- cada ajuste aprovado acrescenta a sua.
create unique index if not exists uq_ponto_marcacao
  on ponto_marcacao (id_colaborador, dt_referencia, tp_marcacao, nvl(id_ajuste, 0));

create table if not exists ponto_espelho_assinatura (
  id_assinatura   number generated by default as identity primary key,
  id_empresa      number       not null,
  id_colaborador  number       not null,
  dt_competencia  date         not null,
  dh_assinatura   timestamp with time zone default systimestamp not null,
  ds_hash         varchar2(64) not null,
  ds_ip           varchar2(64),
  usr_assinatura  varchar2(255),
  constraint fk_ponto_assin_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_ponto_assin_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint uq_ponto_assinatura unique (id_colaborador, dt_competencia)
);

-- Marcação registrada não muda nem some: a correção é uma linha nova (AJUSTE).
-- Só os dados de demonstração (05_dados_demo.sql) podem ser apagados.
create or replace trigger trg_ponto_marcacao_imutavel
  before update or delete on ponto_marcacao
  for each row
begin
  if updating or :old.ds_origem <> 'DEMO' then
    raise_application_error(-20061, 'Marcações de ponto não podem ser alteradas nem apagadas. Solicite um ajuste.');
  end if;
end;
/

-- Marcação que vale por dia e tipo: a do ajuste aprovado mais recente ou, sem
-- ajuste, a original.
create or replace view vw_ponto_marcacao_vigente as
select id_marcacao, id_empresa, id_colaborador, dt_referencia, tp_marcacao,
       dh_marcacao, ds_origem, id_ajuste
  from (select m.*,
               row_number() over (
                 partition by m.id_colaborador, m.dt_referencia, m.tp_marcacao
                 order by case when m.id_ajuste is not null then 0 else 1 end, m.id_marcacao desc
               ) as nr_ordem
          from ponto_marcacao m)
 where nr_ordem = 1;
