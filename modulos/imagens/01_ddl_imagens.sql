-- =============================================================================
-- Corlix Hub · Imagens · cópia das imagens originais antes da otimização
-- Guia: modulos/imagens/Etapas-imagens.md (§1)
--
-- Cada imagem trocada pela página "Otimizar imagens" tem a original guardada
-- aqui, para voltar atrás (guia, "Voltar atrás"). Depois de conferir as imagens
-- novas, o time pode apagar as linhas antigas para liberar espaço.
-- Pode rodar de novo: se a tabela já existir, não faz nada.
-- =============================================================================
declare
  l_qt pls_integer;
begin
  select count(*) into l_qt from user_tables where table_name = 'IMAGEM_ORIGINAL';
  if l_qt = 0 then
    execute immediate q'[
      create table imagem_original (
        id_original  number generated by default on null as identity,
        id_empresa   number         not null,
        nm_tabela    varchar2(30)   not null,
        id_registro  number         not null,
        imagem       blob           not null,
        mime_type    varchar2(255),
        nome_arquivo varchar2(400),
        nr_bytes     number         not null,
        nr_bytes_novo number        not null,
        dh_troca     date           default sysdate not null,
        usr_troca    varchar2(255),
        constraint pk_imagem_original primary key (id_original),
        constraint ck_imagem_original_tabela check (nm_tabela in ('COMUNICADO'))
      )]';
    execute immediate 'create index ix_imagem_original_reg on imagem_original (nm_tabela, id_registro)';
    execute immediate q'[comment on table imagem_original is
      'Imagem original guardada antes de a página Otimizar imagens gravar a versão comprimida.']';
  end if;
end;
