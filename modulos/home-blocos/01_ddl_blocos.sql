--------------------------------------------------------------------------------
-- Corlix Hub · Blocos da Home · 01 · tabelas
-- Reexecutável (if not exists). Dados que a Home (página 1) mostra e que ainda
-- não tinham onde ficar. As telas próprias (Feedbacks, PDI, Férias...) estão
-- nos protótipos de pen_dev/ e vão reaproveitar estas tabelas.
--
-- feedback           -> reconhecimentos e sugestões entre colaboradores
-- pesquisa           -> pesquisa de clima aberta (link externo do formulário)
-- pesquisa_resposta  -> quem já respondeu (só a participação, nunca o conteúdo)
-- evento             -> agenda da empresa (os feriados vêm de ponto_feriado)
-- conversa_1a1       -> conversas agendadas entre gestor e colaborador
-- ferias_periodo     -> períodos aquisitivos e dias já gozados
-- pdi / pdi_objetivo -> plano de desenvolvimento e seus objetivos
--------------------------------------------------------------------------------
set define off

create table if not exists feedback (
  id_feedback      number generated by default as identity primary key,
  id_empresa       number          not null,
  id_autor         number          not null,
  id_destinatario  number          not null,
  tp_feedback      varchar2(15)    not null,
  ds_texto         varchar2(1000)  not null,
  tp_visibilidade  varchar2(20)    default 'PESSOA' not null,
  dh_criacao       timestamp with time zone default systimestamp not null,
  dh_exclusao      timestamp with time zone,
  constraint fk_feedback_empresa      foreign key (id_empresa)      references empresa (id_empresa),
  constraint fk_feedback_autor        foreign key (id_autor)        references colaborador (id_colaborador),
  constraint fk_feedback_destinatario foreign key (id_destinatario) references colaborador (id_colaborador),
  constraint ck_feedback_tipo         check (tp_feedback in ('RECONHECIMENTO', 'SUGESTAO')),
  constraint ck_feedback_visibilidade check (tp_visibilidade in ('PESSOA', 'PESSOA_E_GESTAO')),
  constraint ck_feedback_proprio      check (id_autor <> id_destinatario)
);
create index if not exists ix_feedback_destinatario on feedback (id_destinatario, dh_criacao);

create table if not exists pesquisa (
  id_pesquisa    number generated by default as identity primary key,
  id_empresa     number          not null,
  ds_titulo      varchar2(150)   not null,
  ds_descricao   varchar2(500),
  dt_abertura    date            not null,
  dt_fechamento  date            not null,
  fl_anonima     boolean         default true not null,
  nr_minutos     number(3),
  ds_link        varchar2(1000)  not null,
  constraint fk_pesquisa_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint ck_pesquisa_periodo check (dt_fechamento >= dt_abertura)
);

create table if not exists pesquisa_resposta (
  id_resposta     number generated by default as identity primary key,
  id_pesquisa     number not null,
  id_colaborador  number not null,
  dh_resposta     timestamp with time zone default systimestamp not null,
  constraint fk_pesq_resp_pesquisa    foreign key (id_pesquisa)    references pesquisa (id_pesquisa) on delete cascade,
  constraint fk_pesq_resp_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint uq_pesq_resp unique (id_pesquisa, id_colaborador)
);

create table if not exists evento (
  id_evento   number generated by default as identity primary key,
  id_empresa  number         not null,
  ds_titulo   varchar2(150)  not null,
  dh_inicio   date           not null,
  dh_fim      date,
  ds_local    varchar2(150),
  constraint fk_evento_empresa foreign key (id_empresa) references empresa (id_empresa)
);
create index if not exists ix_evento_inicio on evento (id_empresa, dh_inicio);

create table if not exists conversa_1a1 (
  id_conversa     number generated by default as identity primary key,
  id_empresa      number        not null,
  id_gestor       number        not null,
  id_colaborador  number        not null,
  dh_conversa     date          not null,
  ds_pauta        varchar2(500),
  st_conversa     varchar2(10)  default 'AGENDADA' not null,
  constraint fk_conversa_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_conversa_gestor      foreign key (id_gestor)      references colaborador (id_colaborador),
  constraint fk_conversa_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint ck_conversa_status      check (st_conversa in ('AGENDADA', 'REALIZADA', 'CANCELADA'))
);
create index if not exists ix_conversa_colaborador on conversa_1a1 (id_colaborador, dh_conversa);

create table if not exists ferias_periodo (
  id_periodo           number generated by default as identity primary key,
  id_empresa           number     not null,
  id_colaborador       number     not null,
  dt_inicio_aquisitivo date       not null,
  dt_fim_aquisitivo    date       not null,
  dt_limite_gozo       date       not null,
  nr_dias_direito      number(2)  default 30 not null,
  nr_dias_gozados      number(2)  default 0  not null,
  constraint fk_ferias_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_ferias_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint ck_ferias_dias        check (nr_dias_gozados between 0 and nr_dias_direito),
  constraint uq_ferias_periodo     unique (id_colaborador, dt_inicio_aquisitivo)
);

create table if not exists pdi (
  id_pdi          number generated by default as identity primary key,
  id_empresa      number         not null,
  id_colaborador  number         not null,
  ds_titulo       varchar2(150)  not null,
  dt_prazo        date,
  st_pdi          varchar2(15)   default 'APROVADO' not null,
  constraint fk_pdi_empresa     foreign key (id_empresa)     references empresa (id_empresa),
  constraint fk_pdi_colaborador foreign key (id_colaborador) references colaborador (id_colaborador),
  constraint ck_pdi_status      check (st_pdi in ('RASCUNHO', 'AGUARDANDO', 'APROVADO', 'AJUSTES', 'ENCERRADO'))
);

create table if not exists pdi_objetivo (
  id_objetivo  number generated by default as identity primary key,
  id_pdi       number         not null,
  ds_titulo    varchar2(200)  not null,
  dt_prazo     date,
  st_objetivo  varchar2(15)   default 'NAO_INICIADO' not null,
  constraint fk_pdi_obj_pdi    foreign key (id_pdi) references pdi (id_pdi) on delete cascade,
  constraint ck_pdi_obj_status check (st_objetivo in ('NAO_INICIADO', 'EM_ANDAMENTO', 'CONCLUIDO'))
);
