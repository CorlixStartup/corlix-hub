--------------------------------------------------------------------------------
-- Corlix Hub · Comunicados · 01 · categorias
-- Reexecutável (if not exists e blocos que conferem o dicionário).
--
-- categoria_comunicado   -> Institucional, Eventos, Benefícios... por empresa
-- comunicado.id_categoria -> categoria do comunicado (nula = sem categoria)
--------------------------------------------------------------------------------
set define off

create table if not exists categoria_comunicado (
  id_categoria  number generated by default as identity primary key,
  id_empresa    number        not null,
  nm_categoria  varchar2(60)  not null,
  nr_ordem      number(3)     default 100 not null,
  fl_ativo      boolean       default true not null,
  constraint fk_cat_com_empresa foreign key (id_empresa) references empresa (id_empresa),
  constraint uq_cat_com_nome    unique (id_empresa, nm_categoria)
);

declare
  l_qt pls_integer;
begin
  select count(*) into l_qt from user_tab_columns
   where table_name = 'COMUNICADO' and column_name = 'ID_CATEGORIA';
  if l_qt = 0 then
    execute immediate 'alter table comunicado add (id_categoria number)';
  end if;

  select count(*) into l_qt from user_constraints
   where table_name = 'COMUNICADO' and constraint_name = 'FK_COM_CATEGORIA';
  if l_qt = 0 then
    execute immediate 'alter table comunicado add constraint fk_com_categoria '
                   || 'foreign key (id_categoria) references categoria_comunicado (id_categoria)';
  end if;
end;
/

create index if not exists ix_com_categoria on comunicado (id_categoria);

-- Categorias iniciais para cada empresa (as que já existem ficam como estão)
merge into categoria_comunicado t
using (select e.id_empresa, c.nm_categoria, c.nr_ordem
         from empresa e
        cross join (select 'Institucional' nm_categoria, 10 nr_ordem from dual union all
                    select 'Eventos',               20 from dual union all
                    select 'Benefícios',            30 from dual union all
                    select 'Saúde e bem-estar',     40 from dual union all
                    select 'Treinamentos',          50 from dual union all
                    select 'Resultados',            60 from dual union all
                    select 'Novos colaboradores',   70 from dual) c) s
   on (t.id_empresa = s.id_empresa and t.nm_categoria = s.nm_categoria)
 when not matched then
   insert (id_empresa, nm_categoria, nr_ordem) values (s.id_empresa, s.nm_categoria, s.nr_ordem);

commit;
